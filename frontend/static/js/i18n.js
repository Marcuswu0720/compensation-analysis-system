// Salary category labels are served by the backend keyed by a stable
// snake_case value (see compute/categories.py's CATEGORY_FIELDS) - this maps
// that same key to an English label without needing a backend change, since
// the backend intentionally stays Chinese-only (see i18n.js's module docstring).
const CATEGORY_LABEL_EN = {
  basic_salary_actual: 'Basic Salary',
  performance_bonus: 'Performance Bonus',
  commission_bonus: 'Commission / Bonus',
  overtime_amount: 'Overtime',
  other_income: 'Other Income',
  employer_statutory_cost: 'Employer Statutory Cost',
  supplemental_bonus: 'Bonus Batch',
  supplemental_backpay: 'Backpay Batch',
  gross_salary: 'Gross Salary',
  net_pay: 'Net Pay',
  deduction_total: 'Employee Deductions',
  hr_cost: 'Total HR Cost',
};

function currentLang() {
  return localStorage.getItem(LANG_STORAGE_KEY) === 'en' ? 'en' : 'zh';
}

function setLang(lang) {
  localStorage.setItem(LANG_STORAGE_KEY, lang === 'en' ? 'en' : 'zh');
  window.location.reload();
}

function t(key, vars) {
  const lang = currentLang();
  let str = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ?? TRANSLATIONS.zh[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return str;
}

// Category labels come from the backend as {value, label} (label always
// Chinese) - this returns the right-language label without touching the
// backend, falling back to the backend's Chinese label if a value is ever
// missing from CATEGORY_LABEL_EN (e.g. a future new category not yet added
// here, so English users still see something rather than a blank cell).
function categoryLabel(cat) {
  const key = cat.value ?? cat.category;
  if (currentLang() === 'en') return CATEGORY_LABEL_EN[key] || cat.label;
  return cat.label;
}

function applyStaticI18n() {
  document.documentElement.lang = currentLang() === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) document.title = t(titleEl.getAttribute('data-i18n'));
}

// A small 中文/EN toggle inserted into a host element (top bar on both
// dashboard.html and login.html) - switching reloads the page since fully
// re-rendering every already-fetched table/chart in place isn't worth the
// added complexity (see README's 已知限制 for the trade-off called out to
// the user); on-screen data is easy to re-query after switching.
function mountLangSwitch(hostEl) {
  const el = document.createElement('div');
  el.className = 'lang-switch';
  const zhBtn = document.createElement('button');
  zhBtn.type = 'button';
  zhBtn.textContent = '中文';
  const enBtn = document.createElement('button');
  enBtn.type = 'button';
  enBtn.textContent = 'EN';
  const lang = currentLang();
  zhBtn.className = lang === 'zh' ? 'active' : '';
  enBtn.className = lang === 'en' ? 'active' : '';
  zhBtn.addEventListener('click', () => { if (currentLang() !== 'zh') setLang('zh'); });
  enBtn.addEventListener('click', () => { if (currentLang() !== 'en') setLang('en'); });
  el.appendChild(zhBtn);
  el.appendChild(enBtn);
  hostEl.appendChild(el);
}

document.addEventListener('DOMContentLoaded', applyStaticI18n);
